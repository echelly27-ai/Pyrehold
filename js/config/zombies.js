export function scaledStats(def, wave, flags) {
  const n = Math.max(1, wave || 1);
  const hpMul = (1 + (n - 1) * 0.065) * (flags?.blood ? 1.4 : 1);
  const dmgMul = 1 + (n - 1) * 0.04;
  const goldMul = (1 + (n - 1) * 0.05) * (flags?.blood ? 1.75 : 1);
  return {
    hp: Math.round(def.hp * hpMul),
    damage: def.damage * dmgMul,
    structureDamage: def.structureDamage * dmgMul,
    goldMul,
    xp: Math.round(def.xp * (1 + (n - 1) * 0.03)),
  };
}
